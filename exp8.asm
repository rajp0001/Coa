
DISPLAY MACRO MSG
    LEA DX, MSG
    MOV AH, 09H
    INT 21H
ENDM

DATA SEGMENT
    USERMSG DB "ENTER YOUR PASSWORD: $"
    CORRECT DB 0AH, 0DH, "PASSWORD MATCHED$"
    WRONG DB 0AH, 0DH, "PASSWORD DOESN'T MATCH$"

    USER_INPUT DB 10, 0, 10 DUP(0)
    PASSWORD DB "APSIT"
DATA ENDS

CODE SEGMENT
ASSUME CS: CODE, DS: DATA

START:
    MOV AX, DATA
    MOV DS, AX
    MOV ES, AX

    DISPLAY USERMSG

    LEA DX, USER_INPUT
    MOV AH, 0AH
    INT 21H

    MOV CL, USER_INPUT+1
    CMP CL, 05H
    JNZ UNMATCH

    LEA SI, USER_INPUT+2
    LEA DI, PASSWORD

    MOV CX, 05H
    CLD
    REPE CMPSB
    JNZ UNMATCH

    DISPLAY CORRECT
    JMP EXIT

UNMATCH:
    DISPLAY WRONG

EXIT:
    MOV AH, 4CH
    INT 21H

CODE ENDS
END START
